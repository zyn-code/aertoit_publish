/**
 * Converts the nine sub-service hero photos to WebP and writes the SQL that
 * attaches them.
 *
 *   node build-subservice-images.mjs
 */
import sharp from 'sharp';
import { readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const OUT = join('..', 'frontend', 'public', 'assets', 'services');
mkdirSync(OUT, { recursive: true });

/** French alt text per slug — describes the work, not the file. */
const ALT = {
  'couverture-en-tuiles': 'Toiture en tuiles mécaniques en terre cuite posée par Aertoit',
  'couverture-en-ardoises': 'Couverture en ardoises sur une maison en cours de rénovation',
  'couverture-en-bac-acier': 'Couverture en bac acier avec gouttière et descente d’eau',
  'solutions-d-isolation-laine-de-verre': 'Panneau de laine de verre destiné à l’isolation de toiture',
  'solutions-d-isolation-laine-de-roche': 'Laine de roche projetée dans des combles perdus',
  'solutions-d-isolation-sarking-fibre-de-bois': 'Panneaux de fibre de bois posés en sarking sur une toiture',
  'solutions-d-isolation-sarking-polyurethane': 'Panneaux de polyuréthane posés en sarking sur une charpente',
  'solutions-d-isolation-actis': 'Isolant mince Actis posé entre chevrons',
  'accessoires-velux': 'Fenêtre de toit VELUX avec store intégré sur une toiture en tuiles',
};

// Windows line endings would leave a trailing \r on every filename.
const picks = readFileSync('subservice-picks.txt', 'utf8')
  .split(/\r?\n/)
  .filter(Boolean)
  .map((l) => l.split('\t').map((s) => s.trim()));

const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "''");
let before = 0;
let after = 0;
const statements = [];

for (const [slug, file] of picks) {
  const src = join('raw', file);
  const dest = join(OUT, `${slug}.webp`);
  const inSize = statSync(src).size;

  await sharp(src).resize({ width: 1100, withoutEnlargement: true })
    .webp({ quality: 82, effort: 5 }).toFile(dest);

  const outSize = statSync(dest).size;
  before += inSize;
  after += outSize;
  console.log(
    `  ${slug.padEnd(46)} ${String(Math.round(inSize / 1024)).padStart(5)} kB -> ` +
    `${String(Math.round(outSize / 1024)).padStart(4)} kB  (-${Math.round((1 - outSize / inSize) * 100)}%)`,
  );

  statements.push(
    `UPDATE \`services\` SET\n` +
    `  \`hero_image\` = '/assets/services/${slug}.webp',\n` +
    `  \`hero_image_alt\` = '${esc(ALT[slug] ?? slug)}'\n` +
    `WHERE \`slug\` = '${esc(slug)}';`,
  );
}

writeFileSync(
  join('..', 'database', 'migrations', '013-subservice-images.sql'),
  '-- Generated by .assets-src/build-subservice-images.mjs — do not edit by hand.\n' +
  '-- Hero photo for each of the nine sub-service pages, taken from the live\n' +
  '-- site and re-encoded as WebP. Picked by excluding images shared across\n' +
  '-- pages, then taking the largest remaining photograph.\n' +
  'USE `aertoit`;\n\n' + statements.join('\n\n') +
  '\n\nSELECT `slug`, `hero_image` IS NOT NULL AS has_photo\n' +
  'FROM `services` WHERE `parent_id` IS NOT NULL ORDER BY `sort_order`;\n',
  'utf8',
);

console.log(
  `\n  total ${Math.round(before / 1024)} kB -> ${Math.round(after / 1024)} kB ` +
  `(-${Math.round((1 - after / before) * 100)}%)\n  wrote 013-subservice-images.sql`,
);
